'use client';

import { useState } from 'react';
import { SERIES_FREQUENCIES } from '@webinar/shared';
import { endpoints } from '@/lib/api';
import {
  PanelButton,
  PanelEmpty,
  PanelInput,
  PanelNote,
  PanelSection,
  errorText,
  usePanelData,
} from './PanelKit';

interface Series {
  id: string;
  frequency: string;
  interval: number;
  count: number | null;
  until: string | null;
  timezone: string;
  cancelledAt: string | null;
}

interface Preview {
  occurrences: string[];
  total: number;
}

const WEEKDAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

/**
 * Recurring series.
 *
 * The preview is generated by the same pure function the server uses to create
 * the rows, so what the host sees here is exactly what will be scheduled.
 */
export function SeriesPanel({ webinarId }: { webinarId: string }) {
  const { data, loading, error, reload } = usePanelData(
    () => endpoints.series(webinarId) as Promise<{ series: Series | null }>,
    [webinarId]
  );

  const [frequency, setFrequency] = useState('WEEKLY');
  const [interval, setInterval] = useState('1');
  const [weekdays, setWeekdays] = useState<number[]>([]);
  const [count, setCount] = useState('4');
  const [until, setUntil] = useState('');
  const [preview, setPreview] = useState<Preview | null>(null);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);

  const series = data?.series ?? null;

  function rule() {
    return {
      frequency,
      interval: Number(interval) || 1,
      byWeekday: frequency === 'WEEKLY' ? weekdays : [],
      count: count ? Number(count) : undefined,
      until: until ? new Date(until).toISOString() : undefined,
    };
  }

  async function runPreview() {
    setBusy(true);
    try {
      const result = await endpoints.previewSeries(webinarId, rule());
      setPreview(result);
      setNotice(null);
    } catch (err) {
      setNotice(errorText(err, 'Could not preview that rule'));
    } finally {
      setBusy(false);
    }
  }

  async function create() {
    setBusy(true);
    try {
      await endpoints.createSeries(webinarId, rule());
      setPreview(null);
      setNotice('Series created — the occurrences are now scheduled.');
      await reload();
    } catch (err) {
      setNotice(errorText(err, 'Could not create the series'));
    } finally {
      setBusy(false);
    }
  }

  async function cancel(id: string) {
    setBusy(true);
    try {
      await endpoints.cancelSeries(id);
      await reload();
    } catch (err) {
      setNotice(errorText(err, 'Could not cancel the series'));
    } finally {
      setBusy(false);
    }
  }

  return (
    <PanelSection
      title="Recurring series"
      description="Repeat this session on a schedule. Each occurrence is a full webinar."
    >
      {error && <PanelNote tone="error">{error}</PanelNote>}
      {notice && <PanelNote tone="info">{notice}</PanelNote>}

      {loading ? (
        <PanelEmpty>Loading…</PanelEmpty>
      ) : series ? (
        <div className="rounded-xl border border-line p-3">
          <div className="flex flex-wrap items-center gap-2">
            <div className="min-w-0 flex-1">
              <p className="text-xs font-medium text-fg">
                {series.frequency.charAt(0) + series.frequency.slice(1).toLowerCase()} · every{' '}
                {series.interval}
              </p>
              <p className="text-[11px] text-subtle">
                {series.count ? `${series.count} occurrences` : 'no fixed count'}
                {series.until && ` · until ${new Date(series.until).toLocaleDateString()}`}
                {series.cancelledAt && ' · cancelled'}
              </p>
            </div>
            {!series.cancelledAt && (
              <PanelButton variant="danger" onClick={() => cancel(series.id)} disabled={busy}>
                Cancel series
              </PanelButton>
            )}
          </div>
        </div>
      ) : (
        <>
          <div className="space-y-2 rounded-xl border border-line bg-panel-2/40 p-3">
            <div className="flex flex-wrap gap-2">
              <select
                value={frequency}
                onChange={(e) => setFrequency(e.target.value)}
                className="h-8 rounded-lg border border-line bg-panel px-2 text-xs text-fg outline-none focus:border-brand-500/50"
              >
                {SERIES_FREQUENCIES.map((f) => (
                  <option key={f} value={f}>
                    {f.charAt(0) + f.slice(1).toLowerCase()}
                  </option>
                ))}
              </select>
              <PanelInput
                value={interval}
                onChange={setInterval}
                type="number"
                placeholder="Every N"
                className="w-24"
              />
              <PanelInput
                value={count}
                onChange={setCount}
                type="number"
                placeholder="Occurrences"
                className="w-28"
              />
              <PanelInput value={until} onChange={setUntil} type="date" className="w-36" />
            </div>

            {frequency === 'WEEKLY' && (
              <div className="flex flex-wrap gap-1.5">
                {WEEKDAYS.map((day, index) => {
                  const on = weekdays.includes(index);
                  return (
                    <button
                      key={day}
                      onClick={() =>
                        setWeekdays((prev) =>
                          on ? prev.filter((d) => d !== index) : [...prev, index]
                        )
                      }
                      className={`h-7 w-11 rounded-lg text-[10px] font-medium transition ${
                        on
                          ? 'bg-brand-500 text-white'
                          : 'border border-line text-muted hover:bg-panel-2'
                      }`}
                    >
                      {day}
                    </button>
                  );
                })}
              </div>
            )}

            <div className="flex flex-wrap items-center justify-between gap-2">
              <p className="text-[11px] text-subtle">
                Preview first — the dates are generated by the same rule the server uses.
              </p>
              <div className="flex gap-2">
                <PanelButton onClick={runPreview} disabled={busy}>
                  Preview
                </PanelButton>
                <PanelButton variant="primary" onClick={create} disabled={busy || !preview}>
                  Create series
                </PanelButton>
              </div>
            </div>
          </div>

          {preview && (
            <div className="rounded-xl border border-line p-3">
              <p className="text-xs font-medium text-fg">
                {preview.total} {preview.total === 1 ? 'occurrence' : 'occurrences'}
              </p>
              <ul className="mt-1.5 space-y-0.5">
                {preview.occurrences.slice(0, 12).map((iso) => (
                  <li key={iso} className="text-[11px] text-muted">
                    {new Date(iso).toLocaleString()}
                  </li>
                ))}
                {preview.occurrences.length > 12 && (
                  <li className="text-[11px] text-subtle">
                    …and {preview.occurrences.length - 12} more
                  </li>
                )}
              </ul>
            </div>
          )}
        </>
      )}
    </PanelSection>
  );
}
